async function fetchJson(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url} → ${res.status}`)
  return res.json()
}

async function resolveHeadshots(userIds) {
  const map = new Map()
  for (let i = 0; i < userIds.length; i += 100) {
    const batch = userIds.slice(i, i + 100)
    const url = `https://thumbnails.roblox.com/v1/users/avatar-headshot?userIds=${batch.join(',')}&size=150x150&format=Png&isCircular=false`
    const json = await fetchJson(url)
    for (const entry of json.data ?? []) {
      if (entry.state === 'Completed' && entry.imageUrl) {
        map.set(entry.targetId, entry.imageUrl)
      }
    }
  }
  return map
}

async function resolveAssets(assetIds) {
  const map = new Map()
  const ids = [...assetIds]
  for (let i = 0; i < ids.length; i += 100) {
    const batch = ids.slice(i, i + 100)
    const url = `https://thumbnails.roblox.com/v1/assets?assetIds=${batch.join(',')}&size=420x420&format=Png&isCircular=false`
    const json = await fetchJson(url)
    for (const entry of json.data ?? []) {
      if (entry.state === 'Completed' && entry.imageUrl) {
        map.set(entry.targetId, entry.imageUrl)
      }
    }
  }
  return map
}

async function downloadBinary(url, outPath) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`download ${url} → ${res.status}`)
  const buf = Buffer.from(await res.arrayBuffer())
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, buf)
}

function writeManifest(headshots, shopFiles, profileFiles) {
  const outFile = resolve(root, 'src/data/robloxImages.generated.ts')
  const headshotEntries = [...headshots.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([id, file]) => `  ${id}: '${file}',`)
    .join('\n')

  const shopEntries = Object.entries(shopFiles)
    .map(([key, file]) => `  ${key}: '${file}',`)
    .join('\n')

  const profileEntries = Object.entries(profileFiles)
    .map(([key, file]) => `  ${key}: '${file}',`)
    .join('\n')

  const content = `/** Generated by scripts/sync-roblox-images.mjs — do not edit manually. */
export const ROBLOX_HEADSHOT_FILES: Record<number, string> = {
${headshotEntries}
}

export const REAL_SHOP_IMAGE_FILES = {
${shopEntries}
} as const

export const REAL_PROFILE_IMAGE_FILES = {
${profileEntries}
} as const
`
  writeFileSync(outFile, content, 'utf8')
  console.log(`[roblox-images] manifest → ${outFile}`)
}

export async function syncRobloxImages() {
  const headshotDir = resolve(root, 'public/roblox-headshots')
  const shopDir = resolve(root, 'public/real-shop')
  const profileDir = resolve(root, 'public/real-profile')
  mkdirSync(headshotDir, { recursive: true })
  mkdirSync(shopDir, { recursive: true })
  mkdirSync(profileDir, { recursive: true })

  const headshotUrls = await resolveHeadshots(CREDIT_USER_IDS)
  const headshotFiles = new Map()

  for (const userId of CREDIT_USER_IDS) {
    const imageUrl = headshotUrls.get(userId)
    if (!imageUrl) {
      console.warn(`[roblox-images] missing headshot for user ${userId}`)
      continue
    }
    const rel = `roblox-headshots/${userId}.png`
    const out = resolve(root, 'public', rel)
    if (!existsSync(out)) {
      await downloadBinary(imageUrl, out)
    }
    headshotFiles.set(userId, rel)
  }

  const assetIds = [
    ...Object.values(SHOP_ASSETS),
    ...Object.values(PROFILE_ASSETS),
  ]
  const assetUrls = await resolveAssets(assetIds)

  const shopFiles = {}
  for (const [key, assetId] of Object.entries(SHOP_ASSETS)) {
    const imageUrl = assetUrls.get(assetId)
    if (!imageUrl) {
      console.warn(`[roblox-images] missing shop asset ${key} (${assetId})`)
      continue
    }
    const rel = `real-shop/${assetId}.png`
    const out = resolve(root, 'public', rel)
    if (!existsSync(out)) {
      await downloadBinary(imageUrl, out)
    }
    shopFiles[key] = rel
  }

  const profileFiles = {}
  for (const [key, assetId] of Object.entries(PROFILE_ASSETS)) {
    const imageUrl = assetUrls.get(assetId)
    if (!imageUrl) continue
    const rel = `real-profile/${assetId}.png`
    const out = resolve(root, 'public', rel)
    if (!existsSync(out)) {
      await downloadBinary(imageUrl, out)
    }
    profileFiles[key] = rel
  }

  writeManifest(headshotFiles, shopFiles, profileFiles)
  console.log(
    `[roblox-images] synced ${headshotFiles.size} headshots, ${Object.keys(shopFiles).length} shop, ${Object.keys(profileFiles).length} profile assets`,
  )
}

const isDirectRun =
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href

if (isDirectRun) {
  syncRobloxImages().catch((err) => {
    console.error('[roblox-images]', err)
    process.exit(1)
  })
}
